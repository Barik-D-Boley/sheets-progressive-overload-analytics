// Builds proposed exercise names from migration/exercise-name-map.csv using the
// naming rules in src/backend/naming.js, writes them back to the CSV's
// proposed_name column, and generates src/backend/legacy-name-map.js.
// Edit movement / equipment / detail in the CSV, then run `npm run build:map`.
const fs = require('fs');
const path = require('path');
const vm = require('vm');

function parseCsv(text) {
  const rows = [];
  let row = [], field = '', quoted = false;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (quoted) {
      if (ch === '"' && text[i + 1] === '"') { field += '"'; i++; }
      else if (ch === '"') quoted = false;
      else field += ch;
    } else if (ch === '"') quoted = true;
    else if (ch === ',') { row.push(field); field = ''; }
    else if (ch === '\n' || ch === '\r') {
      if (ch === '\r' && text[i + 1] === '\n') i++;
      row.push(field); rows.push(row); row = []; field = '';
    } else field += ch;
  }
  if (field || row.length) { row.push(field); rows.push(row); }
  return rows.filter(r => r.some(Boolean));
}

const root = path.join(__dirname, '..');
const naming = vm.createContext({});
vm.runInContext(fs.readFileSync(path.join(root, 'src', 'backend', 'naming.js'), 'utf8'), naming);

const csvPath = path.join(root, 'migration', 'exercise-name-map.csv');
const [header, ...rows] = parseCsv(fs.readFileSync(csvPath, 'utf8'));
const col = name => {
  const i = header.indexOf(name);
  if (i < 0) throw new Error('CSV is missing column ' + name);
  return i;
};

const entries = rows.map(r => {
  const movement = r[col('movement')];
  const name = movement ? naming.formatExerciseName({ movement, equipment: r[col('equipment')], detail: r[col('detail')] }) : '';
  r[col('proposed_name')] = name;
  return { legacy: r[col('legacy_name')], name, type: r[col('type')] || 'lift',
    review: r[col('needs_review')] === 'YES', note: r[col('note')] || '' };
});

const cell = v => /[",\n]/.test(v) ? '"' + v.replace(/"/g, '""') + '"' : v;
fs.writeFileSync(csvPath, [header, ...rows].map(r => r.map(cell).join(',')).join('\n') + '\n');

const out = `// GENERATED by tools/build-name-map.js from migration/exercise-name-map.csv - do not edit.
// Default proposals for the "Migration Review" tab; the reviewed tab is what the import uses.
var DEFAULT_LEGACY_NAME_MAP = ${JSON.stringify(entries, null, 1)};
`;
fs.writeFileSync(path.join(root, 'src', 'backend', 'legacy-name-map.js'), out);
console.log(`Wrote ${entries.length} legacy names -> ${new Set(entries.map(e => e.name).filter(Boolean)).size} exercises`);
